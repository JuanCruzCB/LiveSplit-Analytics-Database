/* All the dates between 2020 and 2030. */

DROP TABLE IF EXISTS dates;
CREATE TABLE dates AS
SELECT (generate_series(
    DATE '2020-01-01',
    DATE '2030-12-31',
    INTERVAL '1 day'
))::date AS date;


